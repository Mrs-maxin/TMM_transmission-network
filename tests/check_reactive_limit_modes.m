function rows = check_reactive_limit_modes()
%CHECK_REACTIVE_LIMIT_MODES Deterministic check of reactive-limit mode switching on IEEE14.
% Claim C0. Reactive load is changed at chosen buses so that PV units reach
% their upper or lower limits singly, together, or over several rounds. The
% batch power flow with reactive limits (derivation Section 2.3) is compared
% with MATPOWER Newton-Raphson (pf.enforce_q_lims=1, slack unlimited) in final
% operating mode, node voltage and unit reactive output.
projectRoot = string(fileparts(fileparts(mfilename("fullpath"))));
addpath(char(projectRoot));
yearRoot = fileparts(char(projectRoot));
config = struct("networkFile", fullfile(projectRoot, "data", "networks", "ieee14", "case14.m"), ...
    "matpowerRoot", string(fullfile(fileparts(yearRoot), "00codezip", "matpower8.0")), ...
    "aqppfRoot", string(fullfile(yearRoot, "[1]ACPPF_TMM")), ...
    "aqppfReferenceCommit", "0d5c999db4cbee2ea7055844d31b729d9694d747", ...
    "resultDir", fullfile(projectRoot, "result", "ieee14_reactive_limit_check"), ...
    "powerFlowTolerance", 1e-10, "reactiveTolerance", 5e-6);
cases = [ ...
    struct("name", "基准断面", "bus", 1, "deltaQ_MVAr", 0), ...
    struct("name", "2号机越上限", "bus", 2, "deltaQ_MVAr", 15), ...
    struct("name", "3号机越上限", "bus", 3, "deltaQ_MVAr", 20), ...
    struct("name", "6号机越下限", "bus", 6, "deltaQ_MVAr", -25), ...
    struct("name", "8号机越下限", "bus", 8, "deltaQ_MVAr", -25), ...
    struct("name", "2号、3号机同时越上限", "bus", [2, 3], "deltaQ_MVAr", [15, 20]), ...
    struct("name", "节点4无功负荷增加", "bus", 4, "deltaQ_MVAr", 40), ...
    struct("name", "节点4、5、9无功负荷增加", "bus", [4, 5, 9], "deltaQ_MVAr", [30, 20, 30])];
dependencies = TMM_Transmission_utils.io.setup_external_dependencies(config);
TMM_Transmission_utils.io.ensure_dir(config.resultDir);
mpc = TMM_Transmission_core.powerflow.release_slack_reactive_limits(loadcase(char(config.networkFile)));
count = numel(cases);
loadP = repmat(mpc.bus(:, 3).', count, 1);
loadQ = repmat(mpc.bus(:, 4).', count, 1);
for j = 1:count
    loadQ(j, cases(j).bus) = loadQ(j, cases(j).bus) + cases(j).deltaQ_MVAr;
end
fast = TMM_Transmission_core.powerflow.map_load_samples_with_reactive_limits(mpc, loadP, loadQ, ...
    PowerFlowTolerance=config.powerFlowTolerance, ReactiveTolerance=config.reactiveTolerance);
exact = TMM_Transmission_core.powerflow.solve_reference_power_flow(mpc, loadP, loadQ, ...
    PowerFlowTolerance=config.powerFlowTolerance, EnforceReactiveLimits=true);
rows = struct([]);
for j = 1:count
    row = struct("case", cases(j).name, "changedBuses", strjoin(string(cases(j).bus), " "), ...
        "deltaQ_MVAr", strjoin(string(cases(j).deltaQ_MVAr), " "), ...
        "newtonMode", local_label(exact.modeState(j, :), mpc), "batchMode", local_label(fast.modeState(j, :), mpc), ...
        "modesEqual", isequal(exact.modeState(j, :), fast.modeState(j, :)), "batchRounds", fast.rounds(j), ...
        "maximumVoltageErrorPu", max(abs(fast.voltage(j, :) - exact.voltage(j, :))), ...
        "maximumUnitReactiveErrorMVAr", max(abs(fast.generatorQ(j, :) - exact.generatorQ(j, :))));
    if isempty(rows), rows = row; else, rows(end+1) = row; end %#ok<AGROW>
end
writetable(struct2table(rows), fullfile(config.resultDir, "reactive_limit_modes.csv"));
record = struct("entry", "tests/check_reactive_limit_modes.m", "config", config, "dependencies", dependencies, ...
    "finishedAt", string(datetime("now", "Format", "yyyy-MM-dd HH:mm:ss")));
fid = fopen(fullfile(config.resultDir, "run_manifest.json"), "w");
fprintf(fid, "%s", jsonencode(record, PrettyPrint=true));
fclose(fid);
end

function label = local_label(state, mpc)
fixed = find(state ~= 0);
if isempty(fixed), label = "全部PV机组调压"; return; end
parts = strings(1, numel(fixed));
for k = 1:numel(fixed)
    limitName = "上限"; if state(fixed(k)) < 0, limitName = "下限"; end
    parts(k) = mpc.gen(fixed(k), 1) + "号机" + limitName;
end
label = strjoin(parts, "、");
end
