function rows = summarize_accuracy_by_quantity(errors, method, k)
%SUMMARIZE_ACCURACY_BY_QUANTITY Accuracy and precision per electrical quantity class.
% Classes: PQ-bus voltage magnitude (p.u.), non-slack voltage angle (deg),
% branch active power at both ends (MW) and branch reactive power at both ends
% (MVAr). Mean error gives the bias; standard-deviation ratio and 1%/99%
% quantile errors in physical units give the spread and tails; KS gives the
% whole-distribution difference. Objects without fluctuation in the AC
% reference (PV terminal voltages held at set point) are excluded.
arguments
    errors table
    method (1,1) string
    k (1,1) double
end
classes = struct( ...
    "name", ["PQ节点电压幅值", "节点电压相角", "线路有功", "线路无功"], ...
    "unit", ["p.u.", "deg", "MW", "MVAr"]);
masks = { ...
    errors.quantity == "voltage" & errors.busType == "PQ", ...
    errors.quantity == "voltageAngle", ...
    ismember(errors.quantity, ["linePfrom", "linePto"]), ...
    ismember(errors.quantity, ["lineQfrom", "lineQto"])};
rows = struct([]);
for c = 1:numel(masks)
    mask = masks{c} & errors.referenceVariance > 1e-14;
    if ~any(mask), continue; end
    e = errors(mask, :);
    stdRatio = abs(sqrt(e.modelVariance./e.referenceVariance) - 1);
    [~, worst] = max(e.KS);
    q01 = abs(e.q01Model - e.q01Reference);
    q99 = abs(e.q99Model - e.q99Reference);
    row = struct("method", method, "K", k, "quantity", classes.name(c), "unit", classes.unit(c), ...
        "objectCount", height(e), ...
        "meanErrorMedian", median(e.meanAbsoluteError), "meanErrorMax", max(e.meanAbsoluteError), ...
        "stdRelativeErrorMedian", median(stdRatio), "stdRelativeErrorMax", max(stdRatio), ...
        "q01ErrorMedian", median(q01), "q01ErrorMax", max(q01), ...
        "q99ErrorMedian", median(q99), "q99ErrorMax", max(q99), ...
        "KSMedian", median(e.KS), "KSP90", prctile(e.KS, 90), "KSMax", e.KS(worst), ...
        "KSMaxObject", e.quantity(worst) + "#" + e.index(worst), ...
        "shareKSAtMost003", mean(e.KS <= 0.03));
    if isempty(rows), rows = row; else, rows(end+1) = row; end %#ok<AGROW>
end
end
